def truediv(self: Expr, other: IntoExpr) -> Expr:
    """True division — the pandas ``truediv`` spelling of the ``/`` operator (to Float64).

    Integer operands divide truly rather than truncating, matching Python, Polars
    and DuckDB.

    Args:
        other: The value or expression to divide by.

    Returns:
        A new Float64 expression computing ``self / other``.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"x": [1, 3]})
            >>> ds.select(r=bt.col("x").truediv(2)).to_pydict()
            {'r': [0.5, 1.5]}
    """
    return self / other


