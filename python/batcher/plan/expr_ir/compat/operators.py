"""Method-form spellings of the `Expr` operators (the pandas ``Series.add`` family).

Every operator on `Expr` already has its natural Python spelling (``a + b``,
``a & b``). pandas additionally exposes each as a *named method* — ``s.add(1)``,
``s.eq(1)`` — and code ported from pandas, or generated by a tool that cannot emit
operators, reaches for those names. Each function here delegates straight to the
dunder, so the built plan is byte-identical to the operator spelling.

These are bound onto `Expr` by `compat.bind_compat_methods`; they are written as
free functions here so `core.py` stays the one-`Expr` hierarchy rather than growing
a second, parallel copy of its own operator surface.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from batcher.plan.expr_ir.core import Expr, IntoExpr

__all__ = [
    "add",
    "and_",
    "div",
    "eq",
    "floordiv",
    "ge",
    "gt",
    "le",
    "lt",
    "mod",
    "mul",
    "ne",
    "not_",
    "or_",
    "sub",
    "truediv",
    "xor",
]


def add(self: Expr, other: IntoExpr) -> Expr:
    """Element-wise addition — the pandas ``add`` spelling of the ``+`` operator.

    Args:
        other: The value or expression to add.

    Returns:
        A new expression computing ``self + other``.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"x": [1, 2]})
            >>> ds.select(r=bt.col("x").add(10)).to_pydict()
            {'r': [11, 12]}
    """
    return self + other


