def and_(self: Expr, other: IntoExpr) -> Expr:
    """Boolean AND — the named spelling of the ``&`` operator (SQL three-valued logic).

    Python's ``and`` keyword cannot be overloaded, so this is the spelling for code
    that cannot use the operator form.

    Args:
        other: The predicate to AND with.

    Returns:
        A boolean expression, true where both predicates hold.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"a": [True, True], "b": [True, False]})
            >>> ds.select(r=bt.col("a").and_(bt.col("b"))).to_pydict()
            {'r': [True, False]}
    """
    return self & other


def or_(self: Expr, other: IntoExpr) -> Expr:
    """Boolean OR — the named spelling of the ``|`` operator (SQL three-valued logic).

    Args:
        other: The predicate to OR with.

    Returns:
        A boolean expression, true where either predicate holds.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"a": [True, False], "b": [False, False]})
            >>> ds.select(r=bt.col("a").or_(bt.col("b"))).to_pydict()
            {'r': [True, False]}
    """
    return self | other


def not_(self: Expr) -> Expr:
    """Boolean NOT — the named spelling of the ``~`` operator (SQL three-valued logic).

    Returns:
        A boolean expression, true where the predicate is false.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"a": [True, False]})
            >>> ds.select(r=bt.col("a").not_()).to_pydict()
            {'r': [False, True]}
    """
    return ~self


def xor(self: Expr, other: IntoExpr) -> Expr:
    """Bitwise XOR — the named spelling of the ``^`` operator (operands cast to Int64).

    Args:
        other: The integer expression or value to XOR with.

    Returns:
        A new expression of the XORed bit patterns.

    Examples:
        .. doctest::

            >>> import batcher as bt
            >>> ds = bt.from_pydict({"x": [6]})
            >>> ds.select(r=bt.col("x").xor(3)).to_pydict()
            {'r': [5]}
    """
    return self ^ other
