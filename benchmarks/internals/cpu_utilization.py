"""How much of the CPU budget a query actually uses, and what the operator width costs it.

Two questions, and the second is the reason the first is worth measuring.

**Are the CPU metrics true?** `observe.metrics` reports `cores_busy`, `time_ms_total` and
`threads_max` for every query, and a whole family of decisions is read off them -- the CPU
share a distributed task requests (`kyber.cpu_shares`), the oversubscription verdict that
gates fan-out (`carbonite.policies.cpu_budget`), and every "is the box holding this query
back" finding in `observe.insights`. None of that is worth anything if the counter is wrong,
and nothing else compares it against an independent reading. This does: `resource.getrusage`
over the same window, from outside the engine.

**Is the default operator width right?** `bc_arrow::operator_cores` runs a query on
`physical + (usable - physical) / 3` threads -- every physical core plus a third of the SMT
siblings among them. That fraction is a judgement about the SMT trade, and a judgement about
hardware is a thing to measure rather than argue: on a 2-way-SMT box it caps a query at
roughly two thirds of the logical cores it was granted, so it is also the ceiling on any
utilization target. `ExecutionConfig.parallelism` overrides it, so the sweep below prices the
default against the alternatives on the same query.

**Utilization is not the goal; throughput is.** A width that raises CPU use and lowers
throughput is worse than the default, and the sweep prints both so the trade is visible rather
than implied. Read the `vs default` column first.

Run:
    python benchmarks/internals/cpu_utilization.py
    ROWS=200000000 python benchmarks/internals/cpu_utilization.py
"""

from __future__ import annotations

import dataclasses
import os
import resource
import sys
import threading
import time
from pathlib import Path

import batcher as bt
from batcher import col
from batcher._internal.hardware import available_cpu_count, cpu_oversubscription
from batcher._internal.hardware.engine.detected import engine_hardware
from batcher.config import active_config, config_context
from batcher.observe import metrics_snapshot, reset_metrics, start_metrics, stop_metrics

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from envinfo import machine_fingerprint, require_quiet_box, require_release_build

#: Rows in the probe table. Large enough that thread ramp-up is amortized: at 20M the join
#: below finishes in ~300 ms and the measurement is mostly pool start-up, which reads as low
#: utilization and is not a fact about the engine.
DEFAULT_ROWS = 120_000_000

#: Operator widths to price against the default. `0` is the default (`operator_cores`), and
#: the rest bracket it up to and past the logical core count -- past it on purpose, because a
#: width that keeps improving at the boundary means the boundary is not the limit.
_WIDTH_FRACTIONS = (0.0, 0.67, 0.80, 0.91, 1.00, 1.20)

_REPEATS = 3

#: Sampling rate for the utilization profile. Fast enough to resolve the ramp and the tail
#: on a query of a second or two, cheap enough that the sampler is not itself a co-tenant.
_SAMPLE_HZ = 50.0


def _process_cpu_seconds() -> float:
    """CPU seconds this process and its children have burned, user plus system.

    `getrusage` rather than the engine's own counter, deliberately: the point of the check
    below is that the two agree, and reading one of them twice proves nothing.
    """
    me = resource.getrusage(resource.RUSAGE_SELF)
    kids = resource.getrusage(resource.RUSAGE_CHILDREN)
    return me.ru_utime + me.ru_stime + kids.ru_utime + kids.ru_stime


def _dataset(rows: int):
    """The probe source, generated by the engine rather than in Python.

    A `rows`-long Python list would cost minutes and gigabytes on the control plane, which is
    the side that must never touch a row.
    """
    return bt.range(rows).select(
        a=col("value"),
        b=(col("value") % 977).cast("float64"),
        c=(col("value") % 31).cast("float64"),
    )


def _shapes(rows: int) -> dict:
    """The query shapes swept, chosen for how they load the CPU rather than for coverage.

    A hash join is the most CPU-bound shape the engine has; a grouped aggregate is the most
    common; a sort is the one whose parallel form is hardest. A pure scan-and-filter is
    deliberately absent: it is memory-bandwidth bound, so its utilization says more about the
    machine's DRAM than about the engine's scheduling.
    """
    base = _dataset(rows)
    return {
        "join": lambda: (
            base.select(k=col("a") % 500_000, v=col("b"))
            .join(base.select(k=col("a") % 500_000, w=col("c")), on="k", how="inner")
            .agg(s=col("v").sum())
        ),
        "group_by": lambda: base.group_by(k=col("a") % 100_000).agg(
            s=col("b").sum(), n=col("a").count()
        ),
        "sort": lambda: base.select(k=col("a") % 1_000_003, v=col("b")).sort("k"),
        # The same join with a *grouped* finalize. The `join` shape above ends in a global
        # aggregate -- one output row, so its finalize is serial by construction, and the
        # resulting tail is the query's fault rather than the engine's. Measured: the share of
        # wall below 10% of the budget is 11.1% for `join` and 1.2% here. Any tail this shape
        # still shows is the engine's.
        "join_grouped": lambda: (
            base.select(k=col("a") % 500_000, v=col("b"))
            .join(base.select(k=col("a") % 500_000, w=col("c")), on="k", how="inner")
            .group_by("k")
            .agg(s=col("v").sum())
        ),
    }


def _time_once(dataset) -> tuple[float, float]:
    """One `collect()`, returning `(wall_seconds, cpu_seconds)`."""
    cpu0, wall0 = _process_cpu_seconds(), time.monotonic()
    dataset.collect()
    return time.monotonic() - wall0, _process_cpu_seconds() - cpu0


def measure(build, width: int) -> tuple[float, float]:
    """Best-of-`_REPEATS` `(wall, cpu)` for one shape at one operator width.

    Best-of rather than a median, because the fastest run is the one least perturbed by a
    co-tenant, and this benchmark's whole subject is how many cores were available.
    """
    config = active_config()
    scoped = config.replace(execution=dataclasses.replace(config.execution, parallelism=width))
    with config_context(scoped):
        dataset = build()
        runs = [_time_once(dataset) for _ in range(_REPEATS)]
    return min(runs, key=lambda run: run[0])


def _self_cpu_seconds() -> float:
    """CPU seconds from `/proc/self/stat`, which a sampling thread can read cheaply.

    `getrusage` would do, but this is read fifty times a second from a second thread and
    `/proc/self/stat` is one open and one parse.
    """
    with open("/proc/self/stat") as handle:
        fields = handle.read().rsplit(")", 1)[1].split()
    return (int(fields[11]) + int(fields[12])) / os.sysconf("SC_CLK_TCK")


def _sample_while(run) -> tuple[list[float], float]:
    """Run `run()`, sampling cores-busy at `_SAMPLE_HZ`; return `(samples, wall)`.

    The aggregate `cpu / wall` a sweep reports cannot distinguish a query that held half the
    budget throughout from one that saturated it and then ran a long serial tail. Those want
    opposite fixes, so the shape is sampled rather than averaged.
    """
    samples: list[float] = []
    stop = threading.Event()

    def sampler() -> None:
        previous_wall, previous_cpu = time.monotonic(), _self_cpu_seconds()
        while not stop.is_set():
            time.sleep(1.0 / _SAMPLE_HZ)
            now, cpu = time.monotonic(), _self_cpu_seconds()
            elapsed = now - previous_wall
            if elapsed > 0:
                samples.append((cpu - previous_cpu) / elapsed)
            previous_wall, previous_cpu = now, cpu

    thread = threading.Thread(target=sampler, daemon=True)
    thread.start()
    started = time.monotonic()
    run()
    wall = time.monotonic() - started
    stop.set()
    thread.join(timeout=1.0)
    return samples, wall


def utilization_profile(rows: int) -> None:
    """Mean utilization and the share of wall above 80%, per operator width.

    This is the question a utilization target actually asks, and an average cannot answer it:
    the default width holds a *flat* plateau at `operator_cores` for ~90% of the query and
    still never reaches 80%, because the plateau itself is the cap. Widening moves the
    plateau; it does not remove a tail, and the two are not distinguishable from a mean.
    """
    budget = available_cpu_count()
    build = _shapes(rows)["join_grouped"]
    pressure = cpu_oversubscription()
    print(
        f"\n=== utilization profile (join_grouped, {rows:,} rows, "
        f"oversubscription {pressure:.2f}x) ==="
    )
    if pressure > 1.15:
        # Worth saying loudly, because the two columns fail differently under contention and
        # only one of them looks wrong. Measured on a box at load 69/96 with the widths below:
        # utilization read 64% -> 91% while wall went 50.8s -> 61.2s. The utilization column is
        # still true -- the threads really were on a CPU -- and the wall column is the one that
        # matters, so a reader who takes the headline number here concludes the opposite of the
        # truth. `require_quiet_box` refuses this run by default; `BENCH_ALLOW_BUSY_BOX=1` is
        # how it gets bypassed, and this is what it buys.
        print("  WARNING: the box is contended. The wall column is not usable, and widening")
        print("           raises utilization while *lowering* throughput -- read neither as a")
        print("           recommendation. Re-run on a quiet box.")
    print(f"{'width':>7} {'wall':>8} {'mean cores':>11} {'mean util':>10} {'wall >=80%':>11}")
    for fraction in _WIDTH_FRACTIONS:
        width = 0 if fraction == 0.0 else max(1, round(budget * fraction))
        config = active_config()
        scoped = config.replace(execution=dataclasses.replace(config.execution, parallelism=width))
        with config_context(scoped):
            dataset = build()
            dataset.collect()  # warm: thread pools up, plan cached
            samples, wall = _sample_while(dataset.collect)
        if not samples:
            continue
        mean = sum(samples) / len(samples)
        saturated = len([s for s in samples if s >= 0.8 * budget]) / len(samples)
        label = "default" if width == 0 else str(width)
        print(
            f"{label:>7} {wall:>7.2f}s {mean:>10.1f} {100 * mean / budget:>9.1f}% "
            f"{100 * saturated:>10.1f}%"
        )


def check_the_metrics_are_true(rows: int) -> int:
    """Hold the engine's own CPU counters against an independent reading of the same window.

    Returns:
        `0` when every counter agrees with `getrusage` inside the tolerance, `1` otherwise.
    """
    budget = available_cpu_count()
    start_metrics()
    reset_metrics()
    dataset = _shapes(rows)["join"]()
    wall, cpu = _time_once(dataset)
    engine = metrics_snapshot()["cpu"]
    stop_metrics()

    reported_cpu = engine["time_ms_total"] / 1000.0
    reported_wall = engine["execution_ms_total"] / 1000.0
    print("\n=== are the CPU metrics true? ===")
    print(f"  wall            engine {reported_wall:8.2f}s   getrusage window {wall:8.2f}s")
    print(f"  cpu seconds     engine {reported_cpu:8.2f}s   getrusage        {cpu:8.2f}s")
    print(f"  cores busy      engine {engine['cores_busy']:8.1f}    getrusage {cpu / wall:8.1f}")
    print(f"  threads_max     engine {engine['threads_max']:8d}    of a {budget}-core budget")

    # The engine measures its own execution window and `getrusage` measures the whole call,
    # so the wall figures differ by the control plane's share and are compared loosely. The
    # CPU total is the same quantity on both sides and is held tight.
    if reported_cpu <= 0 or abs(reported_cpu - cpu) / max(cpu, 1e-9) > 0.10:
        print("  MISMATCH: the engine's CPU total disagrees with getrusage by over 10%")
        return 1
    if reported_wall > wall * 1.05:
        print("  MISMATCH: the engine claims a longer execution window than the call took")
        return 1
    print("  OK: the engine's counters agree with an independent reading")
    return 0


def sweep(rows: int) -> None:
    """Price the default operator width against wider ones, on every shape."""
    budget = available_cpu_count()
    widths = []
    for fraction in _WIDTH_FRACTIONS:
        width = 0 if fraction == 0.0 else max(1, round(budget * fraction))
        if width not in widths:
            widths.append(width)

    for name, build in _shapes(rows).items():
        print(
            f"\n### {name}   (rows={rows:,}, best-of-{_REPEATS}, "
            f"oversubscription {cpu_oversubscription():.2f}x)"
        )
        print(f"{'width':>7} {'wall':>9} {'cpu':>10} {'busy':>7} {'util':>8} {'vs default':>11}")
        default_wall = None
        for width in widths:
            wall, cpu = measure(build, width)
            busy = cpu / wall if wall > 0 else 0.0
            if default_wall is None:
                default_wall = wall
            label = "default" if width == 0 else str(width)
            print(
                f"{label:>7} {wall:>8.2f}s {cpu:>9.1f}s {busy:>6.1f} "
                f"{100 * busy / budget:>7.1f}% {default_wall / wall:>10.2f}x"
            )


def main() -> int:
    require_release_build()
    require_quiet_box()
    rows = int(os.environ.get("ROWS", DEFAULT_ROWS))
    hardware = engine_hardware()
    budget = available_cpu_count()

    print(f"machine: {machine_fingerprint()}")
    if hardware:
        width = hardware["physical_cores"] + (budget - hardware["physical_cores"]) // 3
        print(
            f"\nengine sees {hardware['logical_cores']} logical / "
            f"{hardware['physical_cores']} physical cores (SMT {hardware['smt_width']})"
        )
        print(
            f"default operator width is {width} of {budget} -> "
            f"a {100 * width / budget:.0f}% ceiling on utilization before a query runs"
        )

    failed = check_the_metrics_are_true(rows)
    sweep(rows)
    utilization_profile(rows)
    return failed


if __name__ == "__main__":
    sys.exit(main())
