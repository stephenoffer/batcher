#!/usr/bin/env python3
"""Generate the per-engine migration reference pages from the migration registry.

Batcher keeps one spelling per capability, so a user arriving from PySpark, Polars, Daft or
Ray Data needs a lookup for every name they already type: the Batcher spelling, whether the
two engines compute the same thing, and what is missing or different when they don't. The
migration registry (`python/batcher/_internal/migration/data/<engine>/*.toml`) already holds
that answer for every public name in each engine's snapshot, and the `AttributeError`
guidance reads the same rows. A hand-kept table would be a third copy that drifts.

So the reference pages under `docs/getting-started/migration/<engine>/` are derived, never
written by hand. Each registry file is a family of names, and each page groups one or more
families so that no page passes the 500-line docs limit and no directory passes twelve
pages. Every table row reads in both directions, and `leaving-batcher.md` inverts the rows
whose status says the two engines agree.

Which codemod directions the pages call implemented is read from `_IMPLEMENTED` in
`python/batcher/migrate/__main__.py` by parsing the file, not importing it, so generating the
docs needs neither `libcst` nor a built engine.

Run it::

    python tools/gen_migration_docs.py           # rewrite the pages
    python tools/gen_migration_docs.py --check   # exit 1 if any page is stale

`tests/docs/test_migration_docs_fresh.py` runs the same comparison in the test suite.
"""

